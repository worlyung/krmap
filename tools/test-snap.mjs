import assert from 'node:assert/strict';
import {loadData,St,R,specToState} from './core.mjs';
const {D,stats}=loadData();
const {S}=await specToState(D,{regions:['대전 유성구','대전 서구'],hideOthers:true},{stats});
const a='si:30200',b='si:30170';
const scene=()=>St.buildScene(D,S,St.createContext({stats,emdReady:true}),1600);
let sc=scene();
assert.ok(sc.regionOffsets[a]&&sc.regionOffsets[b]);
assert.deepEqual(R.snapOffset(D,sc,a,[8,2],[0,0],10).offset,[0,0]);
assert.equal(R.snapOffset(D,sc,a,[11,0],[0,0],10).neighbor,null);
console.log('ok snap 1 가까운 경계 붙이기·먼 거리 자유 이동');
S.offsets[b]=[100,200];sc=scene();
assert.deepEqual(R.snapOffset(D,sc,a,[103,204],[0,0],10).offset,[100,200]);
console.log('ok snap 2 이미 옮긴 이웃에게 붙이기');
S.layout='explode';S.explodeAmt=.4;sc=scene();
const target=sc.regionOffsets[b].map((v,i)=>v-sc.regionOffsets[a][i]);
const snapped=R.snapOffset(D,sc,a,[target[0]+3,target[1]+4],[0,0],10);
assert.equal(snapped.neighbor,b);S.offsets[a]=snapped.offset;sc=scene();
sc.regionOffsets[a].forEach((v,i)=>assert.ok(Math.abs(v-sc.regionOffsets[b][i])<1e-8));
const restored=St.mergeState(St.defaultState(),JSON.parse(St.serialize(S)));
assert.deepEqual(restored.offsets[a],S.offsets[a]);
console.log('ok snap 3 벌려 놓기 보정·저장 복원');
const fake={regionOffsets:{[a]:[0,0],'si:11110':[0,0]}};
assert.equal(R.snapOffset(D,fake,a,[1,1],[0,0],10).neighbor,null);
assert.equal(R.snapOffset(D,{...sc,tiles:true},a,[1,1],S.offsets[a],10).neighbor,null);
assert.equal(R.snapOffset(D,{regionOffsets:{[a]:[0,0]}},a,[1,1],[0,0],10).neighbor,null);
console.log('ok snap 4 비이웃·타일·숨긴 이웃 제외');
for(const [lv,suffix] of [['sido','도'],['si','시'],['si','군'],['sgg','구'],['emd','읍'],['emd','면'],['emd','동']]) {
  const id=Object.keys(D[lv]).find(id=>D[lv][id].nm.endsWith(suffix)&&((D.nb[lv+'>'+lv]||{})[id]||[]).length);
  assert.ok(id,'이웃이 있는 '+suffix);
  const neighbor=D.nb[lv+'>'+lv][id][0],key=lv+':'+id,nkey=lv+':'+neighbor;
  const s=St.defaultState();s.mode='pick';s.pick={lv,ids:[id,neighbor],fit:true,hideOthers:true};s.splitGu=lv==='sgg';
  const sc=St.buildScene(D,s,St.createContext({stats,emdReady:true}),1200);
  assert.equal(R.snapOffset(D,sc,key,[2,3],[0,0],10).neighbor,nkey,suffix+' 붙이기');
}
console.log('ok snap 5 도·시·군·구·읍·면·동 실제 경계 붙이기');
S.layout='real';S.labelPlace='side';S.offsets[a]=[120,80];sc=scene();
const line=sc.lines.find(l=>l.group==='leader'&&l.lv+':'+l.id===a);
const dot=sc.polys.find(p=>p.group==='leader'&&p.lv+':'+p.id===a);
assert.ok(line&&dot);
const endpoint=line.lines[0].at(-1),center=sc.projectPoint(D.si['30200'].lp.map((v,i)=>v+S.offsets[a][i]));
endpoint.forEach((v,i)=>assert.ok(Math.abs(v-center[i])<1e-6));
assert.ok(sc.texts.some(t=>t.lv+':'+t.id===a));
const svg=R.toSVG(sc,{interactive:true});
assert.ok(svg.includes('<path data-k="'+a+'"'));
assert.ok((svg.match(/data-k="si:30200"/g)||[]).length>=4);
console.log('ok snap 6 이동 후 이름·지시점·선 연결 및 SVG 동반 이동');
