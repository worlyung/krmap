import assert from 'node:assert/strict';
import {loadData,specToState,St,R} from './core.mjs';
const {D,stats}=loadData();
const build=async spec=>{const {S}=await specToState(D,spec,{stats});return St.buildScene(D,S,St.createContext({stats,emdReady:true}),1600);};
const base={region:'공주시',sidoLines:true,shadow:false};
const hidden=await build({...base,context:false}),shown=await build({...base,context:true});
assert.ok(shown.polys.some(p=>p.group==='context'));
assert.ok(shown.lines.some(l=>l.group==='sido'));
assert.ok(!hidden.polys.some(p=>p.group==='context'));
assert.ok(!hidden.lines.some(l=>['context','sido'].includes(l.group)));
assert.deepEqual(hidden.polys.filter(p=>['target','neighbor'].includes(p.group)),shown.polys.filter(p=>['target','neighbor'].includes(p.group)));
assert.ok(hidden.polys.every(p=>p.stroke));
const svg=R.toSVG(hidden);
assert.ok(!svg.includes('id="시도경계"')&&!svg.includes('id="배경"'));
console.log('ok context 1 공주시 배경 끄기·켜기와 지역 경계 보존');
const pick=await build({regions:['공주시','세종시'],unit:'시군구',hideOthers:true,sidoLines:true});
assert.ok(!pick.lines.some(l=>l.group==='sido'));
assert.ok(!pick.polys.some(p=>p.group==='context'));
const national=await build({nationalUnit:'시군구',sidoLines:true});
assert.ok(national.lines.some(l=>l.group==='sido'));
console.log('ok context 2 직접 고르기 배경 숨김·전국 경계 유지');
